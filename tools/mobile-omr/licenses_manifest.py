"""Keep notices and exact local-resource hashes with the offline runtime."""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import zipfile
from prepare import OUT, ROOT, CACHE, get, PYODIDE, ORT, HOMR_COMMIT, PARTSONG_COMMIT, MODELS

LICENSE_URLS={
 'PYODIDE-LICENSE.txt':'https://raw.githubusercontent.com/pyodide/pyodide/main/LICENSE',
 'ONNXRUNTIME-LICENSE.txt':'https://raw.githubusercontent.com/microsoft/onnxruntime/main/LICENSE',
 'ONNXRUNTIME-THIRD-PARTY.txt':'https://raw.githubusercontent.com/microsoft/onnxruntime/main/ThirdPartyNotices.txt',
 'CPYTHON-LICENSE.txt':'https://raw.githubusercontent.com/python/cpython/v3.14.2/LICENSE',
 'HOMR-LICENSE-FAQ.md':'https://raw.githubusercontent.com/liebharc/homr/main/LICENSE_FAQ.md',
}

def main():
    license_dir=OUT/'licenses'
    license_dir.mkdir(parents=True,exist_ok=True)
    for name,url in LICENSE_URLS.items(): get(url,license_dir/name)
    with zipfile.ZipFile(CACHE/'homr-source.zip') as archive:
        base='homr-'+HOMR_COMMIT+'/'
        for src,dest in [('LICENSE','HOMR-LICENSE.txt')]:
            (license_dir/dest).write_bytes(archive.read(base+src))
    for wheel in (OUT/'pyodide').glob('*.whl'):
        with zipfile.ZipFile(wheel) as archive:
            for info in archive.infolist():
                if info.is_dir() or not any(word in info.filename.lower() for word in ['license','copying','thirdparty','third-party']): continue
                if info.file_size>4*1024*1024: continue
                name=wheel.name.split('-')[0]+'-'+info.filename.replace('/','_')
                (license_dir/name).write_bytes(archive.read(info))
    # Only discard generated bytecode within this task-owned runtime directory.
    for item in OUT.rglob('*.pyc'):
        if OUT.resolve() not in item.resolve().parents: raise ValueError('Unexpected cleanup path')
        item.unlink()
    for item in sorted(OUT.rglob('__pycache__'),reverse=True):
        if not any(item.iterdir()): item.rmdir()
    files=[]
    for file in sorted(OUT.rglob('*')):
        if not file.is_file() or file.name=='manifest.json': continue
        files.append({'path':file.relative_to(OUT).as_posix(),'bytes':file.stat().st_size,'sha256':hashlib.sha256(file.read_bytes()).hexdigest()})
    data={
      'format':1,'engine':'homr','homrCommit':HOMR_COMMIT,'partsongCommit':PARTSONG_COMMIT,'offline':True,
      'workerContract':{'init':{'type':'init','runId':'validated native session id','rpcBase':'same-origin /__omr_rpc__/{runId}/'},'recognise':{'type':'recognise','id':'string or number','image':'ArrayBuffer of encoded JPEG or PNG'},'result':{'type':'result','runId':'original session id','id':'original id','xml':'MusicXML string','ms':'milliseconds'},'transport':'native-rpc binary v1; separate Python and ORT workers','maxPacketBytes':67108864,'chunkBytes':524288,'cancel':'terminate both workers and cancel native RPC session'},
      'runtimeVersions':{'pyodide':'314.0.7','python':'3.14.2','onnxruntime-web':'1.30.0'},
      'sources':{
        'homr':'https://github.com/liebharc/homr/tree/'+HOMR_COMMIT,
        'bridge':'https://github.com/pzfreo/partsong/tree/'+PARTSONG_COMMIT,
        'pyodide':PYODIDE,'onnxruntime-web':ORT,
        'models':['https://github.com/liebharc/homr/releases/download/onnx_checkpoints/'+name+'.zip' for name in MODELS],
        'licenses':LICENSE_URLS,
      },
      'modifications':['Workers use only APK-local resources; no CDN and no score upload.','Python and ORT execute in independent workers connected by app-local synchronous-XHR binary RPC.','JSPI/run_sync/callPromising were removed from the active Python bridge; SharedArrayBuffer and cross-origin isolation are not required.','ORT compatibility execution uses CPU/WASM with numThreads=1.','Tensor payloads remain binary; native bridge delivery is chunked rather than serializing tensors as numeric JSON arrays.','Piano runner retains upstream grand-staff grouping, including same-clef staves.','Choir-specific Partsong splitting and key rewriting are not applied.','Partsong JavaScript decoder acceleration and generic zero-duration-rest handling retained.'],
      'workerLoader':'APK-local classic Blob bootstrap imports the two local ES modules and reports import errors with stage and stack.',
      'limits':['Requires classic workers with dynamic ES module import, WebAssembly SIMD, local worker XMLHttpRequest and the app native RPC bridge.','Recognition output requires human review.','Training-data licensing details are preserved in licenses/HOMR-LICENSE-FAQ.md.'],
      'assetBytes':sum(item['bytes'] for item in files),'files':files,
    }
    (OUT/'manifest.json').write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
    print('Manifest:',len(files),'files;',data['assetBytes'],'bytes before manifest',flush=True)

if __name__=='__main__':main()
